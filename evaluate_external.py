"""Evaluate a trained checkpoint on a separate embedding set such as client A/B/C."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import numpy as np
import torch
from frfl.metrics import classification_metrics
from frfl.model import EmbeddingClassifier

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True, help="Checkpoint generated by train.py")
    parser.add_argument("--x", required=True, help="External embeddings .npy")
    parser.add_argument("--y", required=True, help="Identity labels .npy")
    parser.add_argument("--output", default="outputs/external_evaluation.json")
    args = parser.parse_args()
    checkpoint = torch.load(args.model, map_location="cpu", weights_only=True)
    X = np.load(args.x, allow_pickle=False); y = np.load(args.y, allow_pickle=False).astype(str)
    if X.ndim != 2 or y.ndim != 1 or len(X) != len(y):
        raise SystemExit("X must be 2-D; y must be 1-D and have the same number of rows")
    if X.shape[1] != int(checkpoint["embedding_dim"]):
        raise SystemExit("External embedding dimension differs from checkpoint")
    classes = [str(value) for value in checkpoint["classes"]]
    mapping = {name: i for i, name in enumerate(classes)}
    known_mask = np.asarray([label in mapping for label in y], dtype=bool)
    unknown_labels = sorted(set(y[~known_mask].tolist()))
    if not known_mask.any():
        raise SystemExit("No external identities match the checkpoint's training classes")
    model = EmbeddingClassifier(int(checkpoint["embedding_dim"]), int(checkpoint["num_classes"]))
    model.load_state_dict(checkpoint["model_state_dict"]); model.eval()
    with torch.no_grad():
        predictions = model(torch.as_tensor(X[known_mask], dtype=torch.float32)).argmax(1).numpy()
    y_true = np.asarray([mapping[label] for label in y[known_mask]], dtype=np.int64)
    report = {"model_method": checkpoint.get("method", "unknown"),
        "samples_total": int(len(y)), "samples_evaluated_known_identities": int(known_mask.sum()),
        "samples_skipped_unknown_identities": int((~known_mask).sum()), "unknown_identities": unknown_labels,
        "metrics_known_identities": classification_metrics(y_true, predictions),
        "warning": "Use only as an external appearance-shift result if these images were excluded from training and model selection."}
    output = Path(args.output); output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))

if __name__ == "__main__":
    main()
